"""1. Arithmetic Operators
Arithmetic operators are used to perform mathematical operations.

Operator	Description
Addition	Adds two operands
Subtraction	Subtract right operand from left
Multiplication	Multiply two operands
Division	Divide left operand by the right
Modulus	Remainder of the division of left operand by the right
Floor Division	Division that results into whole number
Exponent	Left operand raised to the power of right

"""

# Arithmatic operators


x = 81
y = 9

print('x + y =', x + y)
print('x - y =', x - y)
print('x * y =', x * y)
print('x / y =', x / y)
print('x ** y =', x ** y)
print('x // y =', x // y)

"""
2. Comparison Operators
Comparison operators are used to compare values. They return either True or False.

Operator	Description
Greater than	True if left operand is greater than the right
Less than	True if left operand is less than the right
Equal to	True if both operands are equal
Greater than equal to	True if left operand is greater than or equal to the right
Less than equal to	True if left operand is less than or equal to the right
Not equal to	True if operands are not equal
"""
x=10
y=12 

print('x > y is', x > y)
print('x < y is', x < y)
print('x == y is', x == y)
print('x >= y is', x >= y)
print('x <= y is', x <= y)


